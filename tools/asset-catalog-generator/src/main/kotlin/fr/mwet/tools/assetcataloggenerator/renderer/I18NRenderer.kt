package fr.mwet.tools.assetcataloggenerator.renderer

fun renderI18N(packageName: String, keys: List<String>): String = buildString {
    appendLine("package $packageName")
    appendLine()
    appendLine("import com.badlogic.gdx.utils.I18NBundle")
    appendLine("import ktx.i18n.BundleLine")
    appendLine()
    appendLine("// Generated by asset-catalog-generator from i18n/translations.csv. Do not edit.")
    appendLine("enum class I18N : BundleLine {")
    if (keys.isEmpty()) appendLine("${indent(1)};")
    keys.forEachIndexed { index, key ->
        appendLine("${indent(1)}$key${if (index == keys.lastIndex) ";" else ","}")
    }
    appendLine()
    appendLine("${indent(1)}override val bundle: I18NBundle")
    appendLine("${indent(2)}get() = i18nBundle")
    appendLine()
    appendLine("${indent(1)}companion object {")
    appendLine("${indent(2)}lateinit var i18nBundle: I18NBundle")
    appendLine("${indent(1)}}")
    appendLine("}")
}
