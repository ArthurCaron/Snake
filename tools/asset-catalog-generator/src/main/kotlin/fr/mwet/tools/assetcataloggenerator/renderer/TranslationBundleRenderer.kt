package fr.mwet.tools.assetcataloggenerator.renderer

import fr.mwet.tools.assetcataloggenerator.reader.TranslationTable

fun renderTranslationBundle(table: TranslationTable, language: Int): String = buildString {
    appendLine("# Generated by asset-catalog-generator from i18n/translations.csv. Do not edit.")
    table.rows.forEach { row ->
        appendLine("${row.key}=${row.values[language].replace("\n", "\\n")}")
    }
}
