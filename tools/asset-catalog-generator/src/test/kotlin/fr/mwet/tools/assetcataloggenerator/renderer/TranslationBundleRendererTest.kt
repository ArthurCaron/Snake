package fr.mwet.tools.assetcataloggenerator.renderer

import fr.mwet.tools.assetcataloggenerator.reader.TranslationRow
import fr.mwet.tools.assetcataloggenerator.reader.TranslationTable
import kotlin.test.Test
import kotlin.test.assertEquals

class TranslationBundleRendererTest {
    private val table = TranslationTable(
        languages = listOf("en", "fr"),
        rows = listOf(
            TranslationRow("score", listOf("Score: {0}", "Score : {0}")),
            TranslationRow("lines", listOf("one\ntwo", "un\ndeux")),
        ),
    )

    @Test
    fun `renders one language column as a properties bundle`() {
        assertEquals(
            """
                |# Generated by asset-catalog-generator from i18n/translations.csv. Do not edit.
                |score=Score : {0}
                |lines=un\ndeux
                |
            """.trimMargin(),
            renderTranslationBundle(table, 1),
        )
    }
}
